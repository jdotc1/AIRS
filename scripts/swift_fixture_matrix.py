MINIMUMS = {'free': 80, 'struct': 100, 'enum': 55, 'class': 60,
            'static_type_extension': 45, 'generic': 35, 'protocol': 25,
            'actor_async': 20}
TYPES = ('Int', 'Int32', 'UInt64', 'Double', 'Bool', 'String', '[Int]')
MODES = ('Onone', 'O', 'Osize')


def normalized(name, kind):
    return {'Int': name, 'Int32': f'Int({name})',
            'UInt64': f'Int(truncatingIfNeeded: {name})',
            'Double': f'Int({name}.rounded(.towardZero))',
            'Bool': f'({name} ? 1 : 0)', 'String': f'{name}.utf8.count',
            '[Int]': f'{name}.reduce(0, &+)'}[kind]


def generate():
    shapes = list(itertools.product(TYPES, repeat=3))[:100]
    lines = ['// Generated by scripts/swift_fixture_matrix.py; do not edit.',
             'public enum BroadError: Error { case rejected(Int) }',
             '@inline(never) public func broad_transform(_ value: Int) throws -> Int {',
             '  if value == -12345 { throw BroadError.rejected(value) }; return value &* 3', '}', '']
    cases = []
    for category, count in MINIMUMS.items():
        for local in range(count):
            number = len(cases)
            cid = f'broad_{number:04d}'
            name = f'broad_case_{number:04d}'
            owner = f'BroadOwner{number:04d}'
            kinds = shapes[number % len(shapes)]
            params = ', '.join(f'_ p{i}: {kind}' for i, kind in enumerate(kinds))
            args = ', '.join(f'p{i}' for i in range(3))
            closure = category == 'free' and local % 8 == 0
            typed = number % 7 == 0 and not closure
            throws = 'rethrows' if closure else ('throws(BroadError)' if typed else 'throws')
            generic = '<T: BinaryInteger>' if category == 'generic' else ''
            extra_param = ', _ transform: (Int) throws -> Int' if closure else ''
            extra_arg = ', broad_transform' if closure else ''
            if category == 'generic':
                extra_param = ', _ genericValue: T'
                extra_arg = ', seed'
            async_kw = 'async ' if category == 'actor_async' else ''
            declaration = f'{name}{generic}({params}{extra_param}) {async_kw}{throws} -> Int'
            # Threshold, branch orientation and arithmetic operation are semantic
            # inputs, independent of symbol/owner spelling; all are recorded.
            threshold = 3 + number
            operation = number % 4
            operator = ('&+', '&-', '&*', '^')[operation]
            predicate = ('==', '<', '>')[number % 3]
            score = ' &+ '.join(normalized(f'p{i}', kind) for i, kind in enumerate(kinds))
            if category == 'generic':
                score += ' &+ Int(truncatingIfNeeded: genericValue)'
            if category in ('struct', 'enum', 'class', 'protocol', 'actor_async'):
                score += ' &+ bias'
            body = [f'let score = {score}']
            if closure:
                body += [f'let transformed = try transform(score)', f'return transformed {operator} {threshold}']
            else:
                body += [f'if score {predicate} {threshold} {{ throw BroadError.rejected(score) }}',
                         f'return score {operator} {threshold}']
            method = '@inline(never) public func ' + declaration + ' {\n    ' + '\n    '.join(body) + '\n  }'
            call = name + '(' + args + extra_arg + ')'
            dispatch = 'direct'
            if category == 'free':
                lines.append(method)
                owner_record = 'module'
            elif category == 'generic':
                lines.append(f'public struct {owner} {{\n  {method.replace("public func", "public static func")}\n}}')
                call = owner + '.' + call
                owner_record = owner
                dispatch = 'generic_static'
            elif category == 'struct':
                lines.append(f'public struct {owner} {{ public let bias: Int; public init(_ bias: Int) {{ self.bias = bias }}\n  {method}\n}}')
                call = f'{owner}(seed).' + call
                owner_record = owner
                dispatch = 'value_instance'
            elif category == 'enum':
                lines.append(f'public enum {owner} {{ case value(Int)\n  public var bias: Int {{ switch self {{ case .value(let n): return n }} }}\n  {method}\n}}')
                call = f'{owner}.value(seed).' + call
                owner_record = owner
                dispatch = 'enum_instance'
            elif category == 'class':
                lines.append(f'public class {owner} {{ public let bias: Int; public init(_ bias: Int) {{ self.bias = bias }}\n  {method}\n}}')
                call = f'{owner}(seed).' + call
                owner_record = owner
                dispatch = 'class_instance'
            elif category == 'static_type_extension':
                if local % 3 == 0:
                    lines.append(f'public struct {owner} {{\n  {method.replace("public func", "public static func")}\n}}')
                    dispatch = 'static'
                elif local % 3 == 1:
                    lines.append(f'public class {owner} {{\n  {method.replace("public func", "public class func")}\n}}')
                    dispatch = 'class_type'
                else:
                    lines.append(f'public struct {owner} {{}}\npublic extension {owner} {{\n  {method.replace("public func", "static func")}\n}}')
                    dispatch = 'extension_static'
                call = owner + '.' + call
                owner_record = owner
            elif category == 'protocol':
                proto = owner + 'Protocol'
                # Typed error requirement and implementation agree exactly.
                lines.append(f'public protocol {proto} {{ func {declaration} }}\npublic struct {owner}: {proto} {{\n  public let bias: Int\n  public init(_ bias: Int) {{ self.bias = bias }}\n  {method}\n}}')
                call = 'receiver.' + call
                owner_record = owner
                dispatch = 'protocol_existential'
            else:
                lines.append(f'public actor {owner} {{ public let bias: Int; public init(_ bias: Int) {{ self.bias = bias }}\n  {method}\n}}')
                call = f'{owner}(seed).' + call
                owner_record = owner
                dispatch = 'actor_async'
            callsites = []
            for variant in range(2):
                caller = f'broad_caller_{number:04d}_{variant}'
                caller_params = params + ', _ seed: Int'
                setup = f'let receiver: any {owner}Protocol = {owner}(seed)\n  ' if category == 'protocol' else ''
                await_kw = 'await ' if category == 'actor_async' else ''
                lines.append(f'@inline(never) public func {caller}({caller_params}) {async_kw}-> Int {{\n  {setup}do {{ let result = try {await_kw}{call}; return result {"&+" if variant == 0 else "^"} seed }}\n  catch {{ return seed &- {threshold + variant} }}\n}}')
                callsites.append({'caller': caller, 'expression': 'try ' + await_kw + call,
                                  'variant': variant, 'source_line': len('\n'.join(lines).splitlines()) - 2})
            cases.append({'case_id': cid, 'category': category, 'owner': owner_record,
                          'declaration': declaration, 'raw_symbol_token': name,
                          'signature_shape': json.dumps([list(kinds), 'T:BinaryInteger' if generic else None,
                                                         'throwing_closure' if closure else None, async_kw, throws]),
                          'dispatch': dispatch,
                          'body_semantic': {'normalization': list(kinds), 'predicate': predicate if not closure else 'closure_error',
                                            'threshold': threshold, 'return_operation': operator,
                                            'receiver_bias': category in ('struct', 'enum', 'class', 'protocol', 'actor_async')},
                          'feature_vector': [category, *kinds, dispatch, throws, bool(generic), bool(async_kw),
                                             'closure' if closure else predicate, threshold, operator],
                          'source_callsites': callsites})
            lines.append('')
    manifest = {'schema': 'airs.owned-swift-broad-source.v1', 'evidence_state': 'source_only_uncompiled',
                'emitted_observations': 0, 'minimums': MINIMUMS, 'cases': cases,
                'scope': 'Owned source declarations; source diversity is not emitted ABI/lowering qualification.'}
    return '\n'.join(lines) + '\n', manifest


RETURN_FAMILIES = ('Void', 'Bool', 'Int8', 'UInt8', 'Int16', 'UInt16', 'Int32',
                   'UInt32', 'Int64', 'UInt64', 'Int', 'UInt', 'Float', 'Double',
                   'Int?', 'BroadSmall', 'BroadLarge', 'BroadPayload', 'BroadTag',
                   '(Int, Bool)', 'BroadReference', 'String', 'any BroadValue')
GEOMETRIES = ('handled', 'optional_try', 'forced_try', 'propagation', 'shared_handler_multiple_calls',
              'early_return', 'nested_handlers', 'local_error_conversion', 'noreturn_handler',
              'tail_return', 'inline_absence_challenge', 'defer_cleanup')
# Declaration, call arguments, score expression and independent parameter-family label.
PARAMETER_FORMS = (
    ('', '', '17', 'zero'),
    ('_ input: Int', 'input', 'input', 'one_signed'),
    ('_ flag: Bool, _ narrow: UInt8', 'flag, narrow', '(flag ? 1 : 0) &+ Int(narrow)', 'multi_bool_unsigned'),
    ('_ input: inout Int', '&input', 'input', 'inout'),
    ('_ text: String, _ values: [Int]', 'text, values', 'text.utf8.count &+ values.reduce(0, &+)', 'string_array'),
    ('_ single: Float, _ double: Double', 'single, double', 'Int(single) &+ Int(double)', 'float_double'),
    ('_ maybe: Int?', 'maybe', '(maybe ?? -1)', 'optional'),
    ('_ pair: (Int, Bool)', 'pair', 'pair.0 &+ (pair.1 ? 1 : 0)', 'tuple'),
    ('_ small: BroadSmall', 'small', 'small.value &+ small.other', 'small_aggregate'),
    ('_ reference: borrowing BroadReference', 'reference', 'reference.value', 'borrowing_reference'),
    ('_ owned: consuming BroadSmall', 'owned', 'owned.value &+ owned.other', 'consuming_aggregate'),
    ('_ large: BroadLarge, _ word: UInt64', 'large, word', 'large.a &+ large.h &+ Int(truncatingIfNeeded: word)', 'large_aggregate_unsigned'),
)


def return_expression(kind, score='score'):
    if kind == 'Void': return '()'
    if kind == 'Bool': return f'({score} & 1) == 0'
    if kind in ('Int8', 'UInt8', 'Int16', 'UInt16', 'Int32', 'UInt32', 'Int64', 'UInt64', 'UInt'):
        return f'{kind}(truncatingIfNeeded: {score})'
    if kind == 'Int': return score
    if kind in ('Float', 'Double'): return f'{kind}({score}) / 3'
    if kind == 'Int?': return f'{score} == 0 ? nil : {score}'
    if kind == 'BroadSmall': return f'BroadSmall({score}, {score} &+ 1)'
    if kind == 'BroadLarge': return f'BroadLarge({score})'
    if kind == 'BroadPayload': return f'.payload({score})'
    if kind == 'BroadTag': return f'{score} & 1 == 0 ? .even : .odd'
    if kind == '(Int, Bool)': return f'({score}, {score} > 0)'
    if kind == 'BroadReference': return f'BroadReference({score})'
    if kind == 'String': return f'String({score}, radix: 16)'
    return f'BroadSmall({score}, 1)'


def measure_expression(kind, value='result'):
    if kind == 'Void': return 'seed'
    if kind == 'Bool': return f'({value} ? 1 : 0)'
    if kind in ('Float', 'Double'): return f'Int({value})'
    if kind == 'Int?': return f'({value} ?? seed)'
    if kind in ('BroadSmall', 'BroadReference', 'any BroadValue'): return f'{value}.value'
    if kind == 'BroadLarge': return f'{value}.a &+ {value}.h'
    if kind == 'BroadPayload': return f'{value}.value'
    if kind == 'BroadTag': return f'({value} == .even ? 2 : 3)'
    if kind == '(Int, Bool)': return f'{value}.0 &+ ({value}.1 ? 1 : 0)'
    if kind == 'String': return f'{value}.utf8.count'
    return f'Int(truncatingIfNeeded: {value})'


def generate_v2():
    lines = ['// Owned Swift broad v2: generated, source-only until independently compiled.',
             'public enum BroadError: Error { case rejected(Int) }',
             'public protocol BroadValue: Sendable { var value: Int { get } }',
             'public struct BroadSmall: BroadValue { public let value: Int; public let other: Int; public init(_ value: Int, _ other: Int) { self.value = value; self.other = other } }',
             'public struct BroadLarge: Sendable { public let a,b,c,d,e,f,g,h: Int; public init(_ n: Int) { a=n; b=n &+ 1; c=n &+ 2; d=n &+ 3; e=n &+ 4; f=n &+ 5; g=n &+ 6; h=n &+ 7 } }',
             'public enum BroadPayload: Sendable { case payload(Int); public var value: Int { switch self { case .payload(let n): return n } } }',
             'public enum BroadTag: Sendable, Equatable { case even, odd }',
             'public final class BroadReference: BroadValue { public let value: Int; public init(_ value: Int) { self.value = value } }',
             '@inline(never) public func broad_transform(_ n: Int) throws -> Int { if n == -12345 { throw BroadError.rejected(n) }; return n &* 3 }',
             '@inline(never) public func broad_cleanup(_ value: inout Int) { value &+= 1 }', '']
    cases = []
    for category, minimum in MINIMUMS.items():
        for local in range(minimum):
            n = len(cases)
            name, owner = f'broad_case_{n:04d}', f'BroadOwner{n:04d}'
            kind = RETURN_FAMILIES[n % len(RETURN_FAMILIES)]
            params, args, score, parameter_form = PARAMETER_FORMS[(n // len(RETURN_FAMILIES)) % len(PARAMETER_FORMS)]
            closure = category == 'free' and local % 8 == 0
            typed = n % 7 == 0 and not closure
            throws = 'rethrows' if closure else ('throws(BroadError)' if typed else 'throws')
            generic = '<T: BinaryInteger>' if category == 'generic' else ''
            if closure:
                params = ', '.join(filter(None, (params, '_ transform: (Int) throws -> Int')))
                args = ', '.join(filter(None, (args, 'broad_transform')))
            if generic:
                params = ', '.join(filter(None, (params, '_ genericValue: T')))
                args = ', '.join(filter(None, (args, 'seed')))
                score += ' &+ Int(truncatingIfNeeded: genericValue)'
            asynchronous = category == 'actor_async'
            async_kw = 'async ' if asynchronous else ''
            method_kind = {'free': 'free', 'generic': 'generic_static', 'struct': 'mutating' if local % 2 else 'instance',
                           'enum': ('enum_static' if local % 3 == 0 else ('enum_payload_instance' if local % 3 == 1 else 'enum_empty_instance')),
                           'class': 'final_instance' if local % 2 == 0 else 'virtual_instance',
                           'static_type_extension': ('static' if local % 3 == 0 else ('class_type' if local % 3 == 1 else 'instance_extension')),
                           'protocol': 'protocol_existential', 'actor_async': 'actor_async'}[category]
            has_bias = category in ('struct', 'class', 'protocol', 'actor_async') or method_kind in ('enum_payload_instance', 'enum_empty_instance')
            if has_bias: score += ' &+ bias'
            declaration = f'{name}{generic}({params}) {async_kw}{throws} -> {kind}'
            threshold = n + 3
            op = ('&+', '&-', '^', '&*')[n % 4]
            body = [f'var score = {score}']
            if closure: body += ['score = try transform(score)']
            else: body += [f'if score {("==", "<", ">")[n % 3]} {threshold} {{ throw BroadError.rejected(score) }}']
            if parameter_form == 'inout': body += ['input &+= 1']
            if method_kind == 'mutating': body += ['bias &+= 1']
            body += [f'score = score {op} {threshold}', 'return ' + return_expression(kind)]
            # Explicit inline challenge cases are kept separate from positive noinline cases.
            inline_challenge = n % 12 == 10
            attribute = '@inline(__always)' if inline_challenge else '@inline(never)'
            modifier = 'static ' if method_kind in ('generic_static', 'enum_static', 'static') else ('class ' if method_kind == 'class_type' else ('mutating ' if method_kind == 'mutating' else ''))
            method = f'{attribute} public {modifier}func {declaration} {{\n    ' + '\n    '.join(body) + '\n  }'
            call = name + '(' + args + ')'
            setup = ''
            if category == 'free': lines.append(method); owner_record = 'module'
            elif category == 'generic':
                lines.append(f'public struct {owner} {{\n  {method}\n}}'); call = owner + '.' + call; owner_record = owner
            elif category == 'struct':
                lines.append(f'public struct {owner} {{ public var bias: Int; public init(_ n: Int) {{ bias=n }}\n  {method}\n}}')
                setup = f'var receiver = {owner}(seed)\n  '; call = 'receiver.' + call; owner_record = owner
            elif category == 'enum':
                definition = 'case value(Int); public var bias: Int { switch self { case .value(let n): return n } }' if method_kind == 'enum_payload_instance' else 'case empty; public var bias: Int { 0 }'
                lines.append(f'public enum {owner} {{ {definition}\n  {method}\n}}')
                receiver = f'{owner}.value(seed)' if method_kind == 'enum_payload_instance' else (owner if method_kind == 'enum_static' else f'{owner}.empty')
                call = receiver + '.' + call; owner_record = owner
            elif category == 'class':
                final = 'final ' if method_kind == 'final_instance' else ''
                lines.append(f'public {final}class {owner} {{ public let bias: Int; public init(_ n: Int) {{ bias=n }}\n  {method}\n}}')
                call = f'{owner}(seed).' + call; owner_record = owner
            elif category == 'static_type_extension':
                if method_kind == 'class_type': lines.append(f'public class {owner} {{\n  {method}\n}}'); call = owner + '.' + call
                elif method_kind == 'static': lines.append(f'public struct {owner} {{\n  {method}\n}}'); call = owner + '.' + call
                else:
                    lines.append(f'public struct {owner} {{ public init() {{}} }}\npublic extension {owner} {{\n  {method.replace("public func", "func")}\n}}')
                    call = f'{owner}().' + call
                owner_record = owner
            elif category == 'protocol':
                lines.append(f'public protocol {owner}Protocol {{ func {declaration} }}\npublic struct {owner}: {owner}Protocol {{ public let bias: Int; public init(_ n: Int) {{ bias=n }}\n  {method}\n}}')
                setup = f'let receiver: any {owner}Protocol = {owner}(seed)\n  '; call = 'receiver.' + call; owner_record = owner
            else:
                lines.append(f'public actor {owner} {{ public let bias: Int; public init(_ n: Int) {{ bias=n }}\n  {method}\n}}')
                call = f'{owner}(seed).' + call; owner_record = owner
            expression = ('await ' if asynchronous else '') + call
            callsites = []
            # Generic function callers accept a concrete Int generic argument.
            wrapper_params = params.replace(', _ transform: (Int) throws -> Int', '').replace('_ transform: (Int) throws -> Int', '')
            wrapper_params = wrapper_params.replace(', _ genericValue: T', '').replace('_ genericValue: T', '')
            wrapper_params = ', '.join(filter(None, (wrapper_params, '_ seed: Int')))
            for variant in range(2):
                geometry = GEOMETRIES[(n + variant) % len(GEOMETRIES)]
                if geometry == 'inline_absence_challenge' and not inline_challenge:
                    geometry = 'handled'
                site_params = wrapper_params
                if geometry == 'defer_cleanup':
                    site_params += ', _ cleanup: inout Int'
                caller = f'broad_caller_{n:04d}_{variant}'
                measured = measure_expression(kind)
                result = f'let result = try {expression}; return {measured} &+ seed'
                handled = f'do {{ {result} }} catch {{ return seed &- {threshold} }}'
                caller_throws, caller_result = '', 'Int'
                if geometry == 'optional_try': wrapper_body = f'if let result = try? {expression} {{ return {"result" if kind == "Int?" else measured} }}; return seed'
                elif geometry == 'forced_try': wrapper_body = f'let result = try! {expression}; return {measured}'
                elif geometry == 'propagation': wrapper_body = result; caller_throws = 'throws '
                elif geometry == 'shared_handler_multiple_calls':
                    if parameter_form == 'consuming_aggregate':
                        first_expression = re.sub(r'\bowned\b', 'firstOwned', expression)
                        wrapper_body = f'let firstOwned = BroadSmall(owned.value, owned.other); do {{ _ = try {first_expression}; {result} }} catch {{ return seed }}'
                    else:
                        wrapper_body = f'do {{ _ = try {expression}; {result} }} catch {{ return seed }}'
                elif geometry == 'early_return': wrapper_body = f'if seed == 0 {{ return 7 }}; ' + handled
                elif geometry == 'nested_handlers': wrapper_body = f'do {{ if seed < 0 {{ throw BroadError.rejected(seed) }}; do {{ {result} }} catch {{ return seed &- 1 }} }} catch {{ return seed &+ 2 }}'
                elif geometry == 'local_error_conversion': wrapper_body = f'do {{ {result} }} catch let error as BroadError {{ switch error {{ case .rejected(let n): return n }} }} catch {{ return seed }}'
                elif geometry == 'noreturn_handler': wrapper_body = f'do {{ {result} }} catch {{ fatalError("owned broad v2 rejected") }}'
                elif geometry == 'tail_return': wrapper_body = f'return try {expression}'; caller_throws = 'throws '; caller_result = kind
                elif geometry == 'defer_cleanup': wrapper_body = f'defer {{ broad_cleanup(&cleanup) }}; ' + handled
                else: wrapper_body = handled
                text = f'@inline(never) public func {caller}({site_params}) {async_kw}{caller_throws}-> {caller_result} {{\n  {setup}{wrapper_body}\n}}'
                lines.append(text)
                callsites.append({'caller': caller, 'expression': 'try ' + expression, 'variant': variant,
                                  'geometry': geometry, 'target_inline_attribute': attribute,
                                  'cleanup_observable_caller_inout': geometry == 'defer_cleanup',
                                  'multiple_call_copy': 'explicit_field_copy_before_consumption' if geometry == 'shared_handler_multiple_calls' and parameter_form == 'consuming_aggregate' else None,
                                  'expectation': 'source_only_requires_emitted_validation',
                                  'source_line': len('\n'.join(lines).splitlines()) - 1})
            cases.append({'case_id': f'broad_{n:04d}', 'category': category, 'owner': owner_record,
                          'declaration': declaration, 'raw_symbol_token': name, 'return_family': kind,
                          'parameter_form': parameter_form, 'dispatch': method_kind,
                          'signature_shape': json.dumps([kind, parameter_form, params, throws, async_kw, bool(generic)]),
                          'body_semantic': {'argument_score': score, 'threshold': threshold, 'operation': op,
                                            'return_expression': return_expression(kind), 'mutates_receiver': method_kind == 'mutating',
                                            'mutates_inout': parameter_form == 'inout'},
                          'feature_vector': [category, kind, parameter_form, method_kind, throws, bool(generic), asynchronous, op],
                          'source_callsites': callsites, 'inline_absence_challenge': inline_challenge})
            lines.append('')
    manifest = {'schema': 'airs.owned-swift-broad-source.v2', 'generator_version': 'owned-swift-broad-v2-fixed',
                'evidence_state': 'source_only_uncompiled', 'emitted_observations': 0,
                'minimums': MINIMUMS, 'cases': cases,
                'scope': 'Source ABI-shape expectations only; actual emitted ABI shapes and geometry remain unqualified.'}
    return '\n'.join(lines) + '\n', manifest


def generate_representative():
    """Deterministic set-cover subset, preserving complete owned dependency blocks."""
    source, original = generate_v2()
    def strata(case):
        values = {(key, case[key]) for key in ('category', 'return_family', 'parameter_form', 'dispatch')}
        values.add(('throws', 'rethrows' if 'rethrows' in case['declaration'] else ('typed' if 'throws(BroadError)' in case['declaration'] else 'untyped')))
        values.update(('geometry', site['geometry']) for site in case['source_callsites'])
        return values
    cases = original['cases']
    uncovered = set().union(*(strata(case) for case in cases))
    chosen = []
    while uncovered:
        best = min((case for case in cases if case not in chosen),
                   key=lambda case: (-len(strata(case) & uncovered), case['case_id']))
        chosen.append(best)
        uncovered -= strata(best)
    # Fill to 64 using balanced category counts and stable case ID ties.
    while len(chosen) < 64:
        counts = {category: sum(c['category'] == category for c in chosen) for category in MINIMUMS}
        best = min((case for case in cases if case not in chosen),
                   key=lambda case: (counts[case['category']], case['case_id']))
        chosen.append(best)
    chosen.sort(key=lambda case: case['case_id'])
    ids = {case['case_id'].removeprefix('broad_') for case in chosen}
    chunks = source.split('\n\n')
    selected = [chunks[0]]
    for chunk in chunks[1:]:
        match = re.search(r'func broad_case_(\d{4})', chunk)
        if match and match.group(1) in ids:
            selected.append(chunk)
    manifest = dict(original, generator_version='owned-swift-broad-v2-fixed-representative',
                    qualification_role='representative_second_toolchain', cases=chosen,
                    selection_algorithm='greedy_source_strata_cover_then_balanced_categories_to_64',
                    source_case_count=len(cases), selected_case_ids=[case['case_id'] for case in chosen],
                    strata={key: sorted({value for c in chosen for k, value in strata(c) if k == key})
                            for key in ('category', 'return_family', 'parameter_form', 'dispatch', 'throws', 'geometry')})
    return '\n\n'.join(selected).rstrip() + '\n', manifest


def save_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def write_sources(destination, generation=1, representative=False):
    destination.mkdir(parents=True, exist_ok=True)
    source_path, manifest_path = destination / 'BroadOwned.swift', destination / 'manifest.json'
    if source_path.exists() or manifest_path.exists():
        raise FileExistsError('Source output exists; reuse it or select a new destination')
    source, manifest = generate_representative() if representative else (generate_v2() if generation == 2 else generate())
    source_path.write_text(source)
    save_json(manifest_path, manifest)


